#!/usr/bin/env python3
"""S2 (Astra r2 A#10): the words Fuigo's persisted schema writes (serde tags, renames, keys, variant names), for
fuigo-secrets' at_rest_schema.rs. A recorded value that is a piece of one would rewrite a tag or key and make a record
unloadable, so the at-rest JSON edit never edits a string token that is exactly one of these (code review High 2). Run from the repo root; prints the Rust file. `--check` fails when the
committed file is stale."""
import os, re, sys

ROOTS = [
    "crates/codegen/fuigo-sampling-types/src",
    "crates/codegen/fuigo-shell/src/session",
    "crates/codegen/fuigo-session-events/src",
    "crates/codegen/fuigo-workspace/src/session",
    "crates/codegen/fuigo-tools/src/persistence.rs",
    "crates/codegen/fuigo-shell/src/extensions/notification.rs",
]

def snake(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()

def camel(name):
    s = snake(name).split("_")
    return s[0] + "".join(w.title() for w in s[1:])

def files():
    for root in ROOTS:
        if os.path.isfile(root):
            yield root
            continue
        for d, _, fs in os.walk(root):
            for f in fs:
                if f.endswith(".rs") and not f.endswith("_tests.rs"):
                    yield os.path.join(d, f)

def recordable_shape(w):
    if len(w) < 8:
        return False
    if len(w) >= 16:
        return True
    classes = (any(c.islower() for c in w), any(c.isupper() for c in w), any(c.isdigit() for c in w))
    return sum(classes) > 1

words = set()
tags = {"type"}
for path in files():
    text = open(path, encoding="utf-8").read()
    for attr in re.findall(r"#\[serde\(([^]]*)\)\]", text):
        words.update(re.findall(r'"([A-Za-z0-9_.\-]+)"', attr))
        tags.update(re.findall(r'\btag\s*=\s*"([A-Za-z0-9_]+)"', attr))
    for m in re.finditer(r"#\[serde\([^]]*rename_all\s*=\s*\"(\w+)\"[^]]*\)\]\s*(?:#\[[^]]*\]\s*)*pub(?:\([a-z]+\))?\s+(enum|struct)\s+\w+[^{]*\{(.*?)\n\}", text, re.S):
        style, _, body = m.groups()
        for ident in re.findall(r"^\s{4}(?:pub(?:\([a-z]+\))?\s+)?([A-Za-z][A-Za-z0-9_]*)\s*[:({,]", body, re.M):
            words.add(snake(ident) if "snake" in style else camel(ident) if "camel" in style else ident)
    for ident in re.findall(r"^\s+pub(?:\([a-z]+\))?\s+([a-z][a-z0-9_]*)\s*:", text, re.M):
        words.add(ident)
        words.add(camel(ident))

kept = sorted(w for w in words if recordable_shape(w))
out = ["//! Generated by `scripts/ci/at-rest-schema-words.py` (S2, Astra r2 A#10): words Fuigo's persisted schema writes.",
       "//! A JSON string token that is exactly one of these is never edited at rest (`at_rest::is_schema_word`). Regenerate after",
       "//! changing a persisted type; CI runs the script with `--check`.", "",
       "pub(crate) const WORDS: &[&str] = &["]
out += [f'    "{w}",' for w in kept]
out += ["];", "",
        "/// The serde tag fields of the persisted schema (`#[serde(tag = \"...\")]`): the value of one of these keys is a format",
        "/// label, left unedited when it is exactly one of [`WORDS`] (Sean's S2 decision: by structural position, not by word).",
        ]
one_line = "pub(crate) const TAG_KEYS: &[&str] = &[" + ", ".join(f'"{t}"' for t in sorted(tags)) + "];"
if len(one_line) <= 100:  # rustfmt's width: keep the file fmt-clean
    out += [one_line, ""]
else:
    out += ["pub(crate) const TAG_KEYS: &[&str] = &["] + [f'    "{t}",' for t in sorted(tags)] + ["];", ""]
text = "\n".join(out)
target = "crates/codegen/fuigo-secrets/src/at_rest_schema.rs"
if "--check" in sys.argv:
    if open(target, encoding="utf-8").read() != text:
        sys.exit(f"{target} is stale: run scripts/ci/at-rest-schema-words.py > {target}")
else:
    sys.stdout.write(text)
