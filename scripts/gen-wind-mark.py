#!/usr/bin/env python3
"""Regenerates crates/codegen/fuigo-pager/src/views/welcome/wind_mark_data.rs.

Rasterises the Lucide "Wind" icon (ISC licence, lucide-static 1.59.0) from its
vector strokes (stroke width 2, round caps, 24-unit viewBox) into braille
masks, one per supported size. Each dot is supersampled 8x8 and lit when at
least half of it is covered by the stroke (no erosion, no halftone). Pure
stdlib; no network.

Usage: scripts/gen-wind-mark.py > crates/codegen/fuigo-pager/src/views/welcome/wind_mark_data.rs
"""
import math
import sys

STROKE_HALF = 1.0  # stroke-width 2
SS = 8  # supersampling per dot, per axis
COVERAGE = 0.5  # a dot is lit when at least this fraction of it is inside the stroke
# (cols, rows) in terminal cells; a cell is 2x4 braille dots, so dots are roughly square.
SIZES = [(24, 12), (32, 16), (44, 22), (60, 30)]


class Line:
    def __init__(self, a, b):
        self.a, self.b = a, b

    def dist(self, px, py):
        (ax, ay), (bx, by) = self.a, self.b
        vx, vy = bx - ax, by - ay
        L = vx * vx + vy * vy
        t = 0 if L == 0 else max(0, min(1, ((px - ax) * vx + (py - ay) * vy) / L))
        return math.hypot(px - (ax + t * vx), py - (ay + t * vy))

    def pts(self):
        return [self.a, self.b]


class Arc:
    """SVG endpoint arc (circular, no rotation) as centre, radius and an angle sweep."""

    def __init__(self, p0, p1, r, large, sweep):
        x1, y1 = p0
        x2, y2 = p1
        dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
        d2 = dx * dx + dy * dy
        if d2 > r * r:
            r = math.sqrt(d2)
        sq = max(0.0, (r * r - d2) / d2) ** 0.5
        sign = -1 if large == sweep else 1
        cxp, cyp = sign * sq * dy, sign * sq * -dx
        self.cx, self.cy = cxp + (x1 + x2) / 2, cyp + (y1 + y2) / 2
        self.r = r
        self.a1 = math.atan2(y1 - self.cy, x1 - self.cx)
        a2 = math.atan2(y2 - self.cy, x2 - self.cx)
        da = a2 - self.a1
        if sweep and da < 0:
            da += 2 * math.pi
        if not sweep and da > 0:
            da -= 2 * math.pi
        self.da = da
        self.p0, self.p1 = p0, p1

    def dist(self, px, py):
        ang = math.atan2(py - self.cy, px - self.cx)
        rel = (ang - self.a1) % (2 * math.pi) if self.da >= 0 else (self.a1 - ang) % (2 * math.pi)
        if rel <= abs(self.da):
            return abs(math.hypot(px - self.cx, py - self.cy) - self.r)
        return min(math.hypot(px - self.p0[0], py - self.p0[1]), math.hypot(px - self.p1[0], py - self.p1[1]))

    def pts(self):
        n = 48
        return [
            (self.cx + self.r * math.cos(self.a1 + self.da * i / n), self.cy + self.r * math.sin(self.a1 + self.da * i / n))
            for i in range(n + 1)
        ]


def prims():
    return [
        Arc((12.8, 19.6), (14, 16), 2, 1, 0), Line((14, 16), (2, 16)),   # M12.8 19.6 A2 2 0 1 0 14 16 H2
        Arc((17.5, 8), (19.5, 12), 2.5, 1, 1), Line((19.5, 12), (2, 12)),  # M17.5 8 a2.5 2.5 0 1 1 2 4 H2
        Arc((9.8, 4.4), (11, 8), 2, 1, 1), Line((11, 8), (2, 8)),          # M9.8 4.4 A2 2 0 1 1 11 8 H2
    ]


def raster(cols, rows):
    ps = prims()
    pts = [p for pr in ps for p in pr.pts()]
    x0 = min(p[0] for p in pts) - STROKE_HALF
    x1 = max(p[0] for p in pts) + STROKE_HALF
    y0 = min(p[1] for p in pts) - STROKE_HALF
    y1 = max(p[1] for p in pts) + STROKE_HALF
    W, H = cols * 2, rows * 4
    scale = min(W / (x1 - x0), H / (y1 - y0))
    offx = (W - (x1 - x0) * scale) / 2
    offy = (H - (y1 - y0) * scale) / 2
    need = COVERAGE * SS * SS
    grid = [[False] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            hit = 0
            for sy in range(SS):
                for sx in range(SS):
                    ux = x0 + (x + (sx + 0.5) / SS - offx) / scale
                    uy = y0 + (y + (sy + 0.5) / SS - offy) / scale
                    if any(p.dist(ux, uy) <= STROKE_HALF for p in ps):
                        hit += 1
            grid[y][x] = hit >= need
    return grid


BITS = [[0x01, 0x08], [0x02, 0x10], [0x04, 0x20], [0x40, 0x80]]  # [dy][dx]


def braille(grid, cols, rows):
    out = []
    for r in range(rows):
        row = ""
        for c in range(cols):
            v = 0
            for dy in range(4):
                for dx in range(2):
                    if grid[r * 4 + dy][c * 2 + dx]:
                        v |= BITS[dy][dx]
            row += chr(0x2800 + v)
        out.append(row)
    return out


def main():
    print("// @generated by scripts/gen-wind-mark.py -- do not edit by hand.")
    print("// Lucide \"Wind\" icon, ISC licence (lucide-static 1.59.0); see NOTICE.")
    print("// One solid braille mask per size (8x8 supersampled, 50% coverage); the renderer applies depth and colour.")
    print()
    print("/// `(cols, rows, mask)`, smallest first. Rows are joined by `\\n`.")
    print("pub(super) const MASKS: &[(u16, u16, &str)] = &[")
    for cols, rows in SIZES:
        rows_s = braille(raster(cols, rows), cols, rows)
        print(f"    (\n        {cols},\n        {rows},\n        \"{chr(92)}")
        for i, r in enumerate(rows_s):
            print(f"{r}{chr(92) + 'n' + chr(92) if i < len(rows_s) - 1 else ''}")
        print('",\n    ),')
    print("];")


if __name__ == "__main__":
    main()
